package com.pluralsight;

public class WhileLoop {
    public static void main(String[] args) {

        // Using a while loop, I will print the sentence "I love Java" five times.

        int count = 0;  //Setting the counter at 0
        while (count < 5){  //Making sure it stops at 5
            System.out.println("I Love Java");  //Printing the sentence now
            count++;    // Adding 1 at ech count untill it satid=fies five times

        }

    }
}
